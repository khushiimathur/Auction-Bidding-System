import json
import subprocess
import sys
from pathlib import Path

import streamlit as st

st.set_page_config(
    page_title="Post-Quantum Linkable Ring Signature",
    page_icon="🔐",
    layout="wide",
)

DEMO_DIR = Path(__file__).resolve().parent
REPOSITORY_ROOT = DEMO_DIR.parents[1]
BUILD_DIR = REPOSITORY_ROOT / "build" / "python_demo"
EXECUTABLE_NAME = "lrs_keygen_cli.exe" if sys.platform == "win32" else "lrs_keygen_cli"


@st.cache_resource
def build_keygen_cli():
    subprocess.run(
        ["cmake", "-S", str(DEMO_DIR), "-B", str(BUILD_DIR)],
        check=True,
        capture_output=True,
        text=True,
    )
    subprocess.run(
        ["cmake", "--build", str(BUILD_DIR), "--target", "lrs_keygen_cli", "--config", "Release"],
        check=True,
        capture_output=True,
        text=True,
    )
    candidates = [
        BUILD_DIR / EXECUTABLE_NAME,
        BUILD_DIR / "Release" / EXECUTABLE_NAME,
    ]
    for executable in candidates:
        if executable.is_file():
            return executable
    raise RuntimeError("CMake completed but the key-generation executable was not found.")


def generate_bidders():
    executable = build_keygen_cli()
    result = subprocess.run(
        [str(executable), "5"],
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(result.stdout)


def reset_demo():
    st.session_state.clear()

st.title("Post-Quantum Linkable Ring Signature")
st.caption("Interactive demonstration of the implemented setup, key generation, and ring selection.")

with st.sidebar:
    st.subheader("Demo controls")
    st.button("Reset demo", on_click=reset_demo, use_container_width=True)
    st.caption("Keys are generated locally and kept only in this Streamlit session.")

st.header("Cryptographic Parameters")
demo_parameters, paper_parameters = st.columns(2)

with demo_parameters:
    st.subheader("A. Current Demo Parameters")
    st.error("Demo-only parameters — NOT cryptographically secure.")
    st.table(
        [
            {"Parameter": "n", "Value": "1"},
            {"Parameter": "m", "Value": "2"},
            {"Parameter": "v", "Value": "1"},
            {"Parameter": "d", "Value": "3"},
            {"Parameter": "q", "Value": "101"},
            {"Parameter": "B", "Value": "3"},
        ]
    )

with paper_parameters:
    st.subheader("B. Esgin Paper Reference Parameters")
    st.info("Paper-reported reference configuration — NOT a validated security configuration.")
    st.table(
        [
            {"Parameter": "N", "Value": "64"},
            {"Parameter": "n", "Value": "5"},
            {"Parameter": "m", "Value": "13"},
            {"Parameter": "d", "Value": "256"},
            {"Parameter": "log₂(q)", "Value": "50"},
            {"Parameter": "k", "Value": "2"},
            {"Parameter": "β", "Value": "8"},
            {"Parameter": "r", "Value": "16"},
            {"Parameter": "λ", "Value": "128"},
        ]
    )
    st.markdown(
        "- **N:** ring size.\n"
        "- **n, m:** commitment dimensions.\n"
        "- **d:** polynomial degree.\n"
        "- **q:** modulus; the table reports its bit length, log₂(q).\n"
        "- **k, β:** one-out-of-many proof parameters, with N = βᵏ.\n"
        "- **r:** number of Protocol 2 repetitions.\n"
        "- **λ:** soundness parameter."
    )

st.warning(
    "The current demo uses deliberately tiny parameters for functional testing. "
    "The Esgin paper's reference configuration is provided for comparison only. "
    "The exact modulus, sampler configuration, commitment bounds and computational "
    "security parameters still require validation. λ = 128 does not automatically "
    "imply 128-bit post-quantum security."
)

st.header("1. Key Generation")
st.write(
    "Generate five bidder key pairs using the C++ `RSetup`/`RKeygen` implementation "
    "and the operating-system-backed `SystemRandomSource`."
)
st.caption(
    "Demo parameters: n=1, m=2, v=1, degree=3, q=101, B=3. "
    "These values are intentionally insecure and are for interface demonstration only."
)

if st.button("Generate 5 bidder key pairs", type="primary"):
    try:
        with st.spinner("Building the C++ wrapper and generating keys..."):
            generated = generate_bidders()
        st.session_state["bidders"] = {
            bidder["id"]: bidder for bidder in generated["bidders"]
        }
        st.session_state["parameters"] = generated["parameters"]
        st.session_state["ring_members"] = []
        st.success("Five key pairs generated by the C++ implementation.")
    except (subprocess.CalledProcessError, OSError, RuntimeError, json.JSONDecodeError) as error:
        detail = error.stderr.strip() if isinstance(error, subprocess.CalledProcessError) else str(error)
        st.error(f"Key generation failed: {detail}")

bidders = st.session_state.get("bidders", {})
if bidders:
    st.caption("Each key is a vector of polynomials; each inner list gives low-to-high coefficients in hexadecimal.")
    st.warning(
        "Private components are displayed for this local demo. Do not use these keys "
        "for real identities or secrets."
    )
    for bidder_id, bidder in bidders.items():
        with st.expander(f"{bidder_id} key details"):
            public_column, private_column = st.columns(2)
            with public_column:
                st.markdown("**Public key**")
                st.json(bidder["public_key"])
            with private_column:
                st.markdown("**Private key — secret**")
                st.json(bidder["private_key"])

st.header("2. Ring Formation")
if not bidders:
    st.info("Generate bidder key pairs to form a ring.")
else:
    selected_ids = st.multiselect(
        "Select bidders for the ring",
        options=list(bidders),
        key="ring_members",
    )
    ring_public_keys = [bidders[bidder_id]["public_key"] for bidder_id in selected_ids]
    st.write(f"Ring size: **{len(ring_public_keys)}**")
    if ring_public_keys:
        st.caption(
            "C++-shaped ring value: an ordered list of public keys, where each key "
            "is a vector of polynomial coefficient vectors."
        )
        st.json(ring_public_keys)
        st.write("Members: " + ", ".join(selected_ids))
    else:
        st.warning("The ring is empty. Select at least one bidder.")

st.header("3. Ring Membership Check")
if not bidders:
    st.info("Generate bidder key pairs first.")
else:
    candidate_id = st.selectbox("Bidder to check", options=list(bidders))
    if st.button("Check ring membership"):
        if not selected_ids:
            st.warning("Cannot check membership: the selected ring is empty.")
        else:
            is_member = any(
                bidders[candidate_id]["public_key"] == public_key
                for public_key in ring_public_keys
            )
            if is_member:
                st.success("MEMBER — public key is present in the selected ring.")
            else:
                st.error("NOT A MEMBER — public key is not present in the selected ring.")
    st.caption(
        "This is a basic public-key lookup only. It is not an Esgin cryptographic "
        "RVerify operation."
    )

st.header("4. Esgin Ring Signature")
st.warning("IMPLEMENTATION IN PROGRESS")
st.write(
    "The C++ RSign/RVerify interfaces are present, but this demo has no configured "
    "production hash-to-challenges, full RSign Gaussian and global-rejection "
    "providers, or concrete auxiliary-commitment provider. No mock provider or "
    "fabricated signature is used."
)

st.header("Future extensions")
future_items = [
    "Dilithium one-time signature integration",
    "WCM link-tag generation",
    "Linkability verification",
    "Same-signer / different-signer comparison",
]
for item in future_items:
    st.button(f"{item} — Coming Soon", disabled=True, use_container_width=True)
